    'A rejection supplies no evidence that an earlier acknowledged change was undone. '
    'Do not assume the object remains at a location from an observation before its transfer. '
    'Distinguish a missing task requirement from an invocation error. Compare the rejected '
    'command with the current public interface and the author examples. If the evidence '
    'supports the intended goal step, select its exact callable command. If its prerequisites '
    'are unconfirmed, select a step that establishes a missing prerequisite or answers a '
    'specific unresolved question. Do not invent incompatibility, physical restrictions, '
    'or extra household procedures from Nothing happens. Do not replace the requested '
    'object with a similar type. An already answered question is not a reason to repeat '
    'an inspection. Prior model diagnoses are hypotheses; compare them to actual receipts. '
    'This is one local action, not a new attempt or a complete plan execution. '
    'Return only JSON with exactly three fields: role, reason, action_id. '
    'role is PREPARE for prerequisite/evidence gathering or CORRECT for the local change; '
